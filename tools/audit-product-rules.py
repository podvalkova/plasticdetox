# Store and registry notes carry two kinds of text that are not claims about the
# product: a trailing caveat list, and contrast clauses naming the bad thing this
# product replaces. Classified raw, "a direct swap for the nylon pouf, which
# sheds microplastics" reads as a loofah that sheds microplastics, and
# "Skip bamboo rayon swaddles" reads as an organic cotton swaddle made of rayon.
# Both produced a skip on a researched recommendation, which is the exact
# trade-libel shape the classifier is written to avoid.
CAVEAT = re.compile(r"\bworth knowing\s*:.*$", re.I | re.S)
CONTRAST_CLAUSE = re.compile(
    r"(?:^|(?<=[.;,]))\s*(?:skip|avoid|unlike|instead of|rather than|compared to|"
    r"as opposed to|not like|a (?:direct )?(?:swap|replacement|alternative) for)\b[^.;]*",
    re.I)


# Ways the copy mentions plastic without the product containing any. A steel
# purifier "rather than plastic", a glass jar that "skips the multilayer plastic
# concern", a shell that "never touches the milk", a weight "close to a plastic
# bottle's", and "plastic neutral certified", which is a carbon offset claim and
# not a material at all. All five were scoring as plastic contact.
NOT_CONTACT = re.compile(
    r"\b(?:rather than|instead of|not|no|never|without|avoids?|skips?|replaces?|"
    r"unlike|versus|vs\.?|compared (?:to|with)|as (?:light|heavy) as|close to)\s+"
    r"(?:the\s+|a\s+|an\s+|any\s+)?[\w\s-]{0,24}?plastic\w*[^.;]*"
    r"|plastic\w*[\s-]+(?:neutral|negative|free|offset)"
    r"|\bnever touches\b[^.;]*"
    r"|\bdoes not (?:touch|contact)\b[^.;]*", re.I)

# A source's name is provenance, not a finding. "Lead Safe Mama" put the word
# lead into every note citing them, which cancelled out the very non-detect they
# had published: Weleda Salt Toothpaste, a non detect at a 5 ppb limit, scored
# one hazard against one clean result and came out neutral.
# Only names that contain a hazard word need masking, and only one does. Masking
# the rest cost real signal: MADE SAFE is a certification the classifier scores
# as a testing pass, and it was being replaced with the word "lab".
SOURCE_NAMES = re.compile(r"\blead safe mama\b", re.I)


def clean_note(note):
    """Strip caveats, contrast clauses and source names so only claims remain."""
    n = CAVEAT.sub("", note or "")
    n = CONTRAST_CLAUSE.sub(" ", n)
    n = SOURCE_NAMES.sub("the lab", n)
    n = NOT_CONTACT.sub(" ", n)
    return re.sub(r"\s+", " ", n).strip()


def evidence_text(prod):
    """
    Everything the classifier may read about this row: the display note plus
    the `research` field.

    Research lives in its own field on purpose. The first materials sweep
    appended its facts to the note, and the next build silently deleted 77 of
    121 of them, because store-to-products refreshes store row notes from the
    store data on every run. A field no note-refreshing tool knows about is
    the only text guaranteed to survive the pipeline.

    Cleaned part by part, never as one string: the caveat stripper cuts from
    "Worth knowing:" to the end of its text, and text joined after a note
    that ends in a caveat would be amputated along with it.
    """
    return f"{clean_note(prod.get('note'))} {clean_note(prod.get('research'))}".strip()


MATERIALS_SEG = re.compile(r"\bMaterials:\s*(.+?)(?=\s+Packaging:|$)", re.S)


def formula_evidence(prod):
    """
    Just the formula portion of the research, for the formula read.

    The materials read scans the whole text for hazards, which is right for a
    durable good and wrong for a labelled research field: "creatine powder in
    a plastic tub" vetoed a single ingredient formula pass on the word
    plastic, which describes the tub the packaging front already judged.
    """
    segs = MATERIALS_SEG.findall(prod.get("research") or "")
    return clean_note(" ".join(segs))


