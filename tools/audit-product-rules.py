# ---------------------------------------------------------------- scope, basis

def scope_of(prod):
    """
    Which scope the row's evidence actually covers.

    An ASIN list is a claim about those exact listings. A `match` phrase is a
    named product line, written by hand during research. A `matchAll` group is
    brand words plus a category word, which is a brand level claim narrowed to a
    category, and that is the broadest thing the extension is allowed to show.
    """
    if prod.get("asins"):
        return "sku"
    if prod.get("match"):
        return "line"
    if prod.get("matchAll"):
        # Provenance decides, not the field. brand-lines.py generates groups of
        # brand words plus one category word, which really is a brand level claim
        # narrowed to a category. Every other matchAll names a specific product
        # ("earth mama organic diaper balm", "dyson v15 detect"), which is a
        # product line. Reading them all as brand scope silently demoted 36
        # hand-researched recommendations to "we have not reviewed this".
        return "brand" if prod.get("origin") == "brand-line" else "line"
    return "none"


def basis_of(prod):
    # brand-line rows are generated by projecting a brand verdict onto a
    # category. Everything else was written against a specific product.
    return "inherited" if prod.get("origin") == "brand-line" else "direct"


